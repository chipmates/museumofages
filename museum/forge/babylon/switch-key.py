"""The evidence switch's key: src/wings/babylon/switch-key.ts from the legend's final words and the map plan.

  python3 -I switch-key.py generate <words.md>     write switch-key.ts
  python3 -I switch-key.py check [<words.md>]      every cell against the words, every colour against the map plan's
                                                   classes.shown, its M/R/G and index.html's --ui-class-* tokens;
                                                   exit 1 on any miss

The words file holds a 'Key:' line and a table: | side | EN word | EN line | DE word | DE line |.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MUSEUM = HERE.parent.parent
B = MUSEUM / 'src' / 'wings' / 'babylon'
OUT = B / 'switch-key.ts'
PLAN = B / 'map' / 'map-plan.json'
RECORD = B / 'record.ts'
INDEX = MUSEUM / 'index.html'
ORDER = ['in place', 'found', 'reconstructed', 'typical', 'guessed']
SHOWN = {'in place': 'in place', 'found': 'known', 'reconstructed': 'reconstructed', 'typical': 'typical', 'guessed': 'guessed'}
LETTER = {'M': 'in place', 'R': 'reconstructed', 'G': 'guessed'}
ROWS_AT = 'export const KEY_ROWS: readonly KeyRow[] = '
HEAD_AT = 'export const KEY_HEAD: KeyHead = '

HEADER = """/* THE EVIDENCE SWITCH'S KEY: the five classes the switch paints, in the legend's order, each with its side, colour
   (the map plan's classes.shown), token (index.html), index (record.ts CLASS_TONE), hatch, and its English and German
   word and line. Generated by forge/babylon/switch-key.py from the legend's final words and the map plan; its check
   holds this file to both and to the tokens. */

import type { Shown } from './record'

export type KeyClass = 'in place' | 'found' | 'reconstructed' | 'typical' | 'guessed'
export type Side = 'known' | 'guessed'
export interface KeyWords { word: string; line: string }
export interface KeyRow { id: KeyClass; shown: Shown; side: Side; index: number; colour: string; token: string; hatch: boolean; en: KeyWords; de: KeyWords }
export interface KeyHead { en: { key: string; known: string; guessed: string }; de: { key: string; known: string; guessed: string } }
"""
FOOTER = """
/** each class's colour */
export const KEY_COLOUR = Object.fromEntries(KEY_ROWS.map((r) => [r.id, r.colour])) as Readonly<Record<KeyClass, string>>
/** the record's name of each class: found is the record's known */
export const SHOWN_OF_KEY = Object.fromEntries(KEY_ROWS.map((r) => [r.id, r.shown])) as Readonly<Record<KeyClass, Shown>>
"""


def words(path):
    text = Path(path).read_text()
    m = re.search(r'^Key: (.+?) / (.+?)\. Sides: (.+?) / (.+?), (.+?) / (.+?) \(', text, re.M)
    if not m:
        sys.exit('no Key: line in the words file')
    head = {'en': {'key': m[1], 'known': m[3], 'guessed': m[5]}, 'de': {'key': m[2], 'known': m[4], 'guessed': m[6]}}
    rows = {}
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) != 5 or cells[0] in ('side', '') or set(cells[0]) <= set('-'):
            continue
        cid = cells[1].lower()
        rows[cid] = {'side': cells[0].lower(), 'en': {'word': cells[1], 'line': cells[2]}, 'de': {'word': cells[3], 'line': cells[4]}}
    if sorted(rows) != sorted(ORDER):
        sys.exit(f'the words file names {sorted(rows)}, not the five classes')
    return head, rows


def class_tone():
    m = re.search(r'export const CLASS_TONE: Record<Shown, number> = \{([^}]*)\}', RECORD.read_text())
    return {k.strip().strip("'"): int(v) for k, v in (p.split(':') for p in m[1].split(','))}


def tokens():
    return {k: v.lower() for k, v in re.findall(r'(--ui-class-[a-z-]+):\s*(#[0-9a-fA-F]{6})', INDEX.read_text())}


def build(head, rows):
    shown = json.loads(PLAN.read_text())['classes']['shown']
    tone = class_tone()
    out = []
    for cid in ORDER:
        s = shown[cid]
        out.append({'id': cid, 'shown': SHOWN[cid], 'side': rows[cid]['side'], 'index': tone[SHOWN[cid]], 'colour': s['colour'].lower(),
                    'token': s['token'], 'hatch': bool(s.get('hatch', False)), 'en': rows[cid]['en'], 'de': rows[cid]['de']})
    body = HEAD_AT + json.dumps(head, ensure_ascii=False) + '\n\n' + ROWS_AT + '[\n' + ''.join(
        f'  {json.dumps(r, ensure_ascii=False)},\n' for r in out) + ']\n'
    return HEADER + '\n/** the legend\'s heading and its two sides */\n' + body + FOOTER


def read_ts():
    t = OUT.read_text()
    head = json.loads(t[t.index(HEAD_AT) + len(HEAD_AT):].split('\n', 1)[0])
    arr = t[t.index(ROWS_AT) + len(ROWS_AT):]
    arr = arr[:arr.index('\n]\n') + 2]
    return head, json.loads(re.sub(r',\n\]$', '\n]', arr))


def check(words_path=None):
    misses = []
    head, rows = read_ts()
    plan = json.loads(PLAN.read_text())['classes']
    tok = tokens()
    tone = class_tone()
    if [r['id'] for r in rows] != ORDER:
        misses.append(f'order {[r["id"] for r in rows]}')
    for r in rows:
        s = plan['shown'][r['id']]
        if r['colour'] != s['colour'].lower():
            misses.append(f'{r["id"]}: colour {r["colour"]} against the map plan {s["colour"]}')
        if r['token'] != s['token'] or tok.get(r['token']) != r['colour']:
            misses.append(f'{r["id"]}: token {r["token"]} = {tok.get(r["token"])} in index.html, the key {r["colour"]}')
        if r['index'] != tone[r['shown']]:
            misses.append(f'{r["id"]}: index {r["index"]} against CLASS_TONE {tone[r["shown"]]}')
        if r['hatch'] != (r['side'] == 'guessed'):
            misses.append(f'{r["id"]}: hatch {r["hatch"]} on the {r["side"]} side')
        for lang in ('en', 'de'):
            for cell in ('word', 'line'):
                v = r[lang][cell]
                if not v or re.search('[–—;]', v):
                    misses.append(f'{r["id"]} {lang} {cell}: "{v}" empty or a dash or semicolon')
    for letter, cid in LETTER.items():
        if plan[letter]['colour'].lower() != plan['shown'][cid]['colour'].lower() or plan[letter]['token'] != plan['shown'][cid]['token']:
            misses.append(f'map plan {letter} is not {cid}')
    cells = 5 * 4
    if words_path:
        whead, wrows = words(words_path)
        if whead != head:
            misses.append(f'the heading {head} against the words {whead}')
        for r in rows:
            w = wrows[r['id']]
            for k in ('side', 'en', 'de'):
                if r[k] != w[k]:
                    misses.append(f'{r["id"]} {k}: {r[k]} against the words {w[k]}')
        if OUT.read_text() != build(whead, wrows):
            misses.append('switch-key.ts is not what generate writes from these words: run generate')
    for m in misses:
        print('MISS', m)
    print(f'switch-key check: {len(rows)} classes, {cells} word cells{" against the words file" if words_path else ""}, '
          f'{len(rows)} colours against the map plan and index.html, {len(misses)} misses')
    return 1 if misses else 0


if __name__ == '__main__':
    a = sys.argv[1:]
    if a[:1] == ['generate'] and len(a) == 2:
        OUT.write_text(build(*words(a[1])))
        print(f'wrote {OUT.relative_to(MUSEUM)}')
    elif a[:1] == ['check']:
        sys.exit(check(a[1] if len(a) > 1 else None))
    else:
        sys.exit(__doc__)
